"""Output language translation node.

Translates visible_output_bundle text fields from the module's internal language
(EN) to session_output_language after render_visible and before package_output.
"""
SOURCE_LINES = [
    '    def _translate_output(self, state: RuntimeTurnState) -> RuntimeTurnState:\n',
    '        """Translate visible_output_bundle text fields to session_output_language."""\n',
    '        update = _track(state, node_name="translate_output")\n',
    '        output_lang = str(state.get("session_output_language") or "de").strip().lower()[:2] or "de"\n',
    '\n',
    '        if output_lang == "en":\n',
    '            update["output_translation"] = {"status": "skipped_same_language"}\n',
    '            return update\n',
    '\n',
    '        bundle = dict(state.get("visible_output_bundle") or {})\n',
    '        if not bundle:\n',
    '            update["output_translation"] = {"status": "skipped_empty_bundle"}\n',
    '            return update\n',
    '\n',
    '        texts: list[str] = []\n',
    '        index_map: list[tuple[str, int]] = []\n',
    '\n',
    '        for i, t in enumerate(bundle.get("gm_narration") or []):\n',
    '            texts.append(str(t))\n',
    '            index_map.append(("gm_narration", i))\n',
    '\n',
    '        spoken = bundle.get("spoken_lines") or []\n',
    '        for i, sl in enumerate(spoken):\n',
    '            if isinstance(sl, dict) and sl.get("text"):\n',
    '                texts.append(str(sl["text"]))\n',
    '                index_map.append(("spoken_lines", i))\n',
    '\n',
    '        action = bundle.get("action_lines") or []\n',
    '        for i, al in enumerate(action):\n',
    '            if isinstance(al, dict) and al.get("text"):\n',
    '                texts.append(str(al["text"]))\n',
    '                index_map.append(("action_lines", i))\n',
    '\n',
    '        if not texts:\n',
    '            update["output_translation"] = {"status": "skipped_no_texts"}\n',
    '            return update\n',
    '\n',
    '        model_id, provider, adapter, api_model = self._translation_adapter_candidate()\n',
    '        if adapter is None:\n',
    '            update["output_translation"] = {"status": "adapter_unavailable"}\n',
    '            return update\n',
    '\n',
    '        _lang_label = {"de": "German", "fr": "French", "it": "Italian"}.get(output_lang, output_lang)\n',
    '        numbered = "\\n".join(f"{i}: {t}" for i, t in enumerate(texts))\n',
    '        prompt = (\n',
    '            "Return valid JSON only. No markdown, no explanation.\\n"\n',
    '            f"Translate each numbered text from English to {_lang_label}.\\n"\n',
    '            "Preserve any quoted speech marks exactly as they appear.\\n"\n',
    '            "Return exactly: {\\"translated\\": [\\"<text0>\\", \\"<text1>\\", ...]}\\n"\n',
    '            f"texts:\\n{numbered}"\n',
    '        )\n',
    '\n',
    '        try:\n',
    '            call = adapter.generate(\n',
    '                prompt,\n',
    '                timeout_seconds=30.0,\n',
    '                retrieval_context=None,\n',
    '                model_name=api_model,\n',
    '            )\n',
    '            if not call.success:\n',
    '                update["output_translation"] = {\n',
    '                    "status": "adapter_error_passthrough",\n',
    '                    "adapter_model_id": model_id or None,\n',
    '                    "adapter_provider": provider or None,\n',
    '                    "error": str((call.metadata or {}).get("error") or "")[:300],\n',
    '                }\n',
    '                return update\n',
    '            raw = (call.content or "").strip()\n',
    '            parsed = _safe_json_object_from_model_text(raw)\n',
    '            translated_raw = parsed.get("translated") if isinstance(parsed, dict) else None\n',
    '            translated: list[str] = [str(t) for t in translated_raw] if isinstance(translated_raw, list) else []\n',
    '        except Exception:\n',
    '            update["output_translation"] = {"status": "adapter_error_passthrough"}\n',
    '            return update\n',
    '\n',
    '        if len(translated) != len(texts):\n',
    '            update["output_translation"] = {"status": "length_mismatch_passthrough"}\n',
    '            return update\n',
    '\n',
    '        new_gm = list(bundle.get("gm_narration") or [])\n',
    '        new_spoken = [dict(sl) if isinstance(sl, dict) else sl for sl in (bundle.get("spoken_lines") or [])]\n',
    '        new_action = [dict(al) if isinstance(al, dict) else al for al in (bundle.get("action_lines") or [])]\n',
    '\n',
    '        for idx, (field, pos) in enumerate(index_map):\n',
    '            if field == "gm_narration":\n',
    '                new_gm[pos] = translated[idx]\n',
    '            elif field == "spoken_lines":\n',
    '                new_spoken[pos]["text"] = translated[idx]\n',
    '            elif field == "action_lines":\n',
    '                new_action[pos]["text"] = translated[idx]\n',
    '\n',
    '        bundle["gm_narration"] = new_gm\n',
    '        bundle["spoken_lines"] = new_spoken\n',
    '        bundle["action_lines"] = new_action\n',
    '        update["visible_output_bundle"] = bundle\n',
    '        update["output_translation"] = {\n',
    '            "status": "translated",\n',
    '            "language": output_lang,\n',
    '            "count": len(texts),\n',
    '            "adapter_model_id": model_id or None,\n',
    '            "adapter_provider": provider or None,\n',
    '        }\n',
    '        return update\n',
]
